import fs from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Run ONLY under Node during preparation/build. Browsers import the generated
// functions, never Ajv's runtime compiler (which requires CSP-unsafe eval).
const ajv = new Ajv({ allErrors: true, inlineRefs: false, code: { source: true, esm: true, lines: true }, strict: true });
const content = JSON.parse(await fs.readFile('data/schemas/content.schema.json', 'utf8'));
content.definitions = {};
const definitionsByShape = new Map();
for (const [index, key] of Object.keys(content.properties).entries()) {
  const shape = JSON.stringify(content.properties[key]);
  const id = definitionsByShape.get(shape) ?? `file${index}`;
  if (!definitionsByShape.has(shape)) {
    content.definitions[id] = content.properties[key];
    definitionsByShape.set(shape, id);
  }
  content.properties[key] = { $ref: `#/definitions/${id}` };
}
ajv.addSchema(content, 'content');
ajv.addSchema(JSON.parse(await fs.readFile('data/schemas/save.schema.json', 'utf8')), 'save');
ajv.addSchema(JSON.parse(await fs.readFile('data/schemas/save-v2.schema.json', 'utf8')), 'saveV2');
ajv.addSchema(JSON.parse(await fs.readFile('data/schemas/save-v1.schema.json', 'utf8')), 'saveV1');
let source = standaloneCode(ajv, { validateContent: 'content', validateSave: 'save', validateSaveV2: 'saveV2', validateSaveV1: 'saveV1' });
source = source.replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
source = source.replaceAll('require("ajv/dist/runtime/equal").default', 'deepEqual');
source = 'import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";\n' +
  'import deepEqualModule from "ajv/dist/runtime/equal.js";\n' +
  'const ucs2length = typeof ucs2lengthModule === "function" ? ucs2lengthModule : ucs2lengthModule.default;\n' +
  'const deepEqual = typeof deepEqualModule === "function" ? deepEqualModule : deepEqualModule.default;\n' + source;
const output = '// @ts-nocheck\n// Generated by tools/generate-validators.mjs. Do not edit; JSON Schema is canonical.\n' + source.trimEnd() + '\n';
const target = 'src/infrastructure/schema-validators.js';
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8') !== output) throw new Error('STALE_VALIDATORS: run npm run generate:validators and review the diff');
  console.log('PASS generated validators: source matches schemas/generator; functions not executed.');
} else {
  await fs.writeFile(target, output);
  console.log('Generated content/save v1/v2/v3 standalone validators (CSP-safe).');
}
