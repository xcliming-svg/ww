import fs from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
const ajv = new Ajv({ allErrors: true, inlineRefs: false, code: { source: true, esm: true, lines: true }, strict: true });
const content = JSON.parse(await fs.readFile('data/schemas/content.schema.json', 'utf8'));
content.definitions = {};
const definitionsByShape = new Map();
for (const [index, key] of Object.keys(content.properties).entries()) {
  const shape = JSON.stringify(content.properties[key]); const id = definitionsByShape.get(shape) ?? `file${index}`;
  if (!definitionsByShape.has(shape)) { content.definitions[id] = content.properties[key]; definitionsByShape.set(shape, id); }
  content.properties[key] = { $ref: `#/definitions/${id}` };
}
ajv.addSchema(content, 'content');
ajv.addSchema(JSON.parse(await fs.readFile('data/schemas/save.schema.json', 'utf8')), 'save');
ajv.addSchema(JSON.parse(await fs.readFile('data/schemas/save-v1.schema.json', 'utf8')), 'saveV1');
let source = standaloneCode(ajv, { validateContent: 'content', validateSave: 'save', validateSaveV1: 'saveV1' });
source = source.replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
source = 'import ucs2length from "ajv/dist/runtime/ucs2length.js";\n' + source;
await fs.writeFile('src/infrastructure/schema-validators.js', '// @ts-nocheck\n// Generated by tools/generate-validators.mjs. Do not edit; JSON Schema is canonical.\n' + source.trimEnd() + '\n');
console.log('Generated content/save validators (no runtime schema compilation).');
