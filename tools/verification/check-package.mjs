import fs from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { check, finish, data, files, readJson as read } from './context.mjs';
// Offline renderer must never use Ajv.compile / Function-constructor under CSP.
const staticValidators = await fs.readFile('src/infrastructure/schema-validators.js', 'utf8');
check(
  staticValidators.includes('Generated by tools/generate-validators.mjs'),
  'Schema validators must be precompiled',
);
check(
  !/\bnew\s+Ajv\s*\(|\bnew\s+Function\s*\(/.test(staticValidators),
  'CSP-unsafe runtime schema compilation',
);
check(!/\bfrom\s+['"]ajv['"]/.test(staticValidators), 'Bundled Ajv compiler in runtime validator');
check(!/\brequire\s*\(/.test(staticValidators), 'Unconverted CommonJS call in generated ESM');
for (const [name, module] of [
  ['ucs2length', 'ucs2length'],
  ['deepEqual', 'equal'],
]) {
  check(
    staticValidators.includes(`import ${name}Module from "ajv/dist/runtime/${module}.js";`),
    `Generated helper import:${name}`,
  );
  check(
    staticValidators.includes(
      `const ${name} = typeof ${name}Module === "function" ? ${name}Module : ${name}Module.default;`,
    ),
    `Generated CJS interop guard:${name}`,
  );
  await fs.access(`node_modules/ajv/dist/runtime/${module}.js`);
}
const pkg = await read('package.json'),
  lock = await read('package-lock.json');
check(pkg.dependencies.phaser === '4.2.1', 'Phaser version');
for (const section of ['dependencies', 'devDependencies'])
  check(
    JSON.stringify(Object.entries(pkg[section]).sort()) ===
      JSON.stringify(Object.entries(lock.packages[''][section]).sort()),
    `Lockfile dependency mismatch:${section}`,
  );
for (const version of Object.values({ ...pkg.dependencies, ...pkg.devDependencies }))
  check(/^\d+\.\d+\.\d+$/.test(String(version)), `Unpinned dependency:${version}`);
const desktop = await fs.readFile('desktop/main.cjs', 'utf8');
for (const expression of [
  'contextIsolation: true',
  'nodeIntegration: false',
  'sandbox: true',
  'assertSender',
  'will-navigate',
  'setWindowOpenHandler',
])
  check(desktop.includes(expression), `Missing desktop guard:${expression}`);
for (const file of files.filter((p) => p.startsWith('src/'))) {
  const text = await fs.readFile(file, 'utf8');
  check(
    !/(?:fetch\(|from\s*|import\()['"]https?:\/\//.test(text),
    `Runtime remote dependency:${file}`,
  );
  check(!/steamworks|greenworks|steam-cloud/i.test(text), `Forbidden service:${file}`);
}
const builder = data['desktop/builder.json'];
check(
  builder.asar &&
    builder.files.includes('dist/**/*') &&
    builder.extraResources.some((/** @type {{from:string}} */ r) => r.from.endsWith('OFL.txt')),
  'Package content/license contract',
);
check((await fs.readFile('index.html', 'utf8')).includes('Content-Security-Policy'), 'Missing CSP');
const notices = await fs.readFile('public/licenses/THIRD_PARTY_NOTICES.txt', 'utf8');
for (const [name, version] of Object.entries(pkg.dependencies))
  check(notices.includes(`${name}@${version}`), `Missing runtime notice:${name}`);
check(
  builder.extraResources.some(
    (/** @type {{from:string}} */ r) => r.from === 'public/licenses/THIRD_PARTY_NOTICES.txt',
  ),
  'Missing bundled runtime notices',
);
const syntax = spawnSync(process.execPath, ['--check', 'src/infrastructure/schema-validators.js'], {
  encoding: 'utf8',
});
check(syntax.status === 0, `Generated validator syntax: ${syntax.stderr}`);
finish('package');
